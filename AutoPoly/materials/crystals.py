@dataclass(frozen=True)
class CrystalCell:
    """
    An orthorhombic bulk cell.

    Attributes:
        name: Registry key.
        lengths: (a, b, c) in A.
        fractional: ((element, (fx, fy, fz)), ...).
        periodic: Axes along which the bulk is periodic (graphene: x, y).
        bond_cutoffs: {(elem_a, elem_b): cutoff A} for bond perception.
        citation: Structure reference.
    """
    name: str
    lengths: Tuple[float, float, float]
    fractional: Tuple
    periodic: Tuple[bool, bool, bool] = (True, True, True)
    bond_cutoffs: Dict[Tuple[str, str], float] = field(default_factory=dict)
    citation: str = ""

    @property
    def n_atoms(self) -> int:
        return len(self.fractional)

    @property
    def volume(self) -> float:
        a, b, c = self.lengths
        return a * b * c

    def cartesian(self) -> Tuple[list, np.ndarray]:
        """(elements, Cartesian positions) of one cell."""
        el = [e for e, _ in self.fractional]
        frac = np.array([f for _, f in self.fractional], dtype=float)
        return el, frac * np.asarray(self.lengths)

    def density(self) -> float:
        """Bulk mass density (g/cm^3)."""
        from .structure import element_mass
        mass = sum(element_mass(e) for e, _ in self.fractional)
        return mass / (self.volume * 0.602214076)

    def replicate_around_origin(self, half_extent) -> Tuple[list, np.ndarray]:
        """
        Tile the cell so the tiling covers [-h, h] on every periodic axis
        (h = half_extent, scalar or per axis); non-periodic axes keep one
        layer.  Returns (elements, positions) centered on the origin.
        """
        h = np.broadcast_to(np.asarray(half_extent, dtype=float), (3,))
        el1, pos1 = self.cartesian()
        L = np.asarray(self.lengths)
        ranges = []
        for axis in range(3):
            if self.periodic[axis]:
                n = int(math.ceil(h[axis] / L[axis])) + 1
                ranges.append(range(-n, n))
            else:
                ranges.append(range(0, 1))
        elements, chunks = [], []
        for i in ranges[0]:
            for j in ranges[1]:
                for k in ranges[2]:
                    shift = np.array([i, j, k]) * L
                    chunks.append(pos1 + shift)
                    elements.extend(el1)
        return elements, np.vstack(chunks)


def _fcc(element: str) -> CrystalCell:
    a = FCC_LATTICE[element]
    nn = a / math.sqrt(2.0)
    return CrystalCell(
        name=f"fcc_{element.lower()}",
        lengths=(a, a, a),
        fractional=tuple((element, f) for f in FCC_FRACTIONAL),
        bond_cutoffs={(element, element): 0.5 * (nn + a)},
        citation=f"fcc {element}, a = {a} A (room temperature)",
    )


